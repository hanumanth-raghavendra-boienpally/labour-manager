import { Icon } from './Icon';
import { dateTime, isNew, statusLabel, statusPill } from '../lib/format';

/**
 * The "AI labour forecast" card (dynamic): what the agent wrote into DB1 for one DC and business date.
 * Once the store manager has decided, the same card is shown from the DB2 snapshot of what was decided.
 */
export function ForecastCard({ f, showStatus = false, cardRef, flash = false }) {
  return (
    <div className={`card${flash ? ' flash' : ''}`} ref={cardRef}>
      <h3>
        AI labour forecast {f.code} {isNew(f.receivedAt) && <span className="newtag">NEW</span>}
        {showStatus && <> <span className={statusPill(f.status)}>{statusLabel(f.status)}</span></>}
      </h3>
      <div className="meta">
        <div><span className="muted">Generated</span>{dateTime(f.generatedAt)}</div>
        <div><span className="muted">Generated by</span>{f.generatedBy}{f.agentMode ? ` · ${f.agentMode.toLowerCase()} mode` : ''}</div>
        <div><span className="muted">Workload input</span>{f.workloadSource ?? '—'}</div>
        <div><span className="muted">Version</span>v{f.version} · review cycle {f.reviewCycle}</div>
        <div><span className="muted">Store and date</span>{f.dcName} · {f.dateLabel}</div>
        <div><span className="muted">Coverage</span>{f.coverage ?? '—'}</div>
      </div>
      {f.drivers?.length > 0 && <div style={{ marginTop: 10 }}>{f.drivers.map(d => <span key={d} className="chip">{d}</span>)}</div>}
      {f.narrative && <div className="narrative">{f.narrative.replace(' [simulated]', '')}</div>}
      <div className="src">
        <Icon name="database" size={12} />{' '}
        {f.dataSource === 'DB2'
          ? <>Snapshot in DB2 (workflow) taken at the decision · originally agent_playbook #{f.playbookId} in DB1</>
          : <>Live from DB1 · labor_allocation.agent_playbook #{f.playbookId}</>}
        {' · '}{f.scheduleSource}
      </div>
    </div>
  );
}
